/* ==========================================================================
   АВТОМАТИЧЕСКАЯ ЛЕНИВАЯ ЗАГРУЗКА ДЛЯ ВСЕХ КАРТИНОК НА САЙТЕ (image-lazy-load.js)
   ========================================================================== */

(function() {
  // Находим абсолютно все картинки на странице и нативно включаем им ленивую загрузку
  document.querySelectorAll('img').forEach(function(img) {
    if (!img.hasAttribute('loading')) {
      img.setAttribute('loading', 'lazy');
    }
  });
})();
